CREATE TABLE ops.schema_migration(version text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT clock_timestamp(), description text NOT NULL);
CREATE DOMAIN ref.positive_quantity AS numeric(18,4) CHECK(VALUE>0);
CREATE DOMAIN ref.nonnegative_money AS numeric(18,2) CHECK(VALUE>=0);
CREATE DOMAIN ref.nonblank_text AS text CHECK(length(btrim(VALUE))>0);
CREATE TABLE ref.code_system(id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,uri text NOT NULL UNIQUE,name ref.nonblank_text NOT NULL,version text NOT NULL,is_demo boolean NOT NULL DEFAULT true);
CREATE TABLE ref.concept(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,system_id smallint NOT NULL REFERENCES ref.code_system,code text NOT NULL,display ref.nonblank_text NOT NULL,active boolean NOT NULL DEFAULT true,UNIQUE(system_id,code));
CREATE TABLE ref.unit(code text PRIMARY KEY,label text NOT NULL,dimension text NOT NULL,ucum_code text);
CREATE TABLE ref.currency(code char(3) PRIMARY KEY,label text NOT NULL,minor_units smallint NOT NULL CHECK(minor_units BETWEEN 0 AND 4));
CREATE TABLE ref.encounter_type(code text PRIMARY KEY,label text NOT NULL);
CREATE TABLE ref.service(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code text NOT NULL UNIQUE,name ref.nonblank_text NOT NULL,category text NOT NULL CHECK(category IN('consultation','laboratory','imaging','procedure','bed_day')),active boolean NOT NULL DEFAULT true);
CREATE TABLE ref.test(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code text NOT NULL UNIQUE,name text NOT NULL,unit_code text REFERENCES ref.unit,value_type text NOT NULL CHECK(value_type IN('numeric','text','coded','boolean')),reference_note text NOT NULL DEFAULT 'Synthetic demonstration; no clinical reference interval');
CREATE TABLE ref.test_panel(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code text NOT NULL UNIQUE,name text NOT NULL);
CREATE TABLE ref.panel_item(panel_id integer NOT NULL REFERENCES ref.test_panel,test_id integer NOT NULL REFERENCES ref.test,position smallint NOT NULL CHECK(position>0),PRIMARY KEY(panel_id,test_id),UNIQUE(panel_id,position));
CREATE TABLE ref.medication(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code text NOT NULL UNIQUE,name text NOT NULL,form text NOT NULL,unit_code text NOT NULL REFERENCES ref.unit,is_demo boolean NOT NULL DEFAULT true,active boolean NOT NULL DEFAULT true);
CREATE TABLE ref.route(code text PRIMARY KEY,name text NOT NULL);
